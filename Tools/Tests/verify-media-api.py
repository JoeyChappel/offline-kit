"""Check the isolated review server, including backwards compatibility and portable progress.
Usage: python3 verify-media-api.py http://127.0.0.1:8082
Only use with the synthetic media fixture library generated by make-media-fixtures.py.
"""
import json
import sys
from urllib.request import Request, urlopen
from urllib.parse import urlencode
base = sys.argv[1].rstrip('/')
def catalog(**query):
    return json.load(urlopen(base+'/api/media?'+urlencode(query), timeout=10))
def titles(response):
    index = {i['id']:i for i in response['items']}
    return [index[i]['title'] for i in response['results']]
data = catalog()
expected = {'Across the Valley','Coastal Trail','River Journey','Under the Stars','Evening Light','Quiet Seasons','Sunday Jazz','The Secret Garden','Treasure Island'}
assert set(i['title'] for i in data['items']) == expected, 'This check requires the isolated synthetic fixture library'
required = {'id','kind','category','title','meta','tracks'}
for item in data['items']:
    assert required.issubset(item)
    for track in item['tracks']:
        assert {'title','url'}.issubset(track)
        assert track['url'].startswith('/media/')
assert titles(catalog(filter='video',genre='Adventure',sort='titleDescending')) == ['Coastal Trail','Across the Valley']
music = catalog(filter='music',sort='artist')
assert music['genres'] == ['Folk','Jazz']
assert [a['name'] for a in music['artists']] == ['Mara Ellis','North Street Quartet']
songs = catalog(filter='music',q='Long Way')
index = {i['id']:i for i in songs['items']}
assert len(songs['songs']) == 3
assert all(index[s['item']]['tracks'][s['index']]['title']=='The Long Way Home' for s in songs['songs'])
book = next(i for i in data['items'] if i['title']=='The Secret Garden')
def progress(track, seconds, finished):
    req=Request(base+'/api/media/progress',data=json.dumps({'id':book['id'],'track':track,'seconds':seconds,'finished':finished}).encode(),headers={'Content-Type':'application/json'})
    assert json.load(urlopen(req,timeout=5))['ok']
def current():
    return next(i for i in catalog()['items'] if i['id']==book['id'])['progress']
progress(1,12,False)
assert current()['track']==1 and current()['seconds']==12 and not current()['finished']
progress(1,0,True)
assert current()['finished']
progress(0,0,False)
assert current()['track']==0 and current()['seconds']==0 and not current()['finished']
video = next(i for i in data['items'] if i['title']=='Across the Valley')
req = Request(base+video['tracks'][0]['url'],headers={'Range':'bytes=0-31'})
with urlopen(req,timeout=5) as response:
    assert response.status==206 and len(response.read())==32
assert video.get('upNext') in [i['id'] for i in data['items'] if i['title']=='Coastal Trail']
print('PASS: compatible media contract, genres, sort order, artist albums, song search, chapter resume, finish/start-over persistence, Up Next and range streaming.')
